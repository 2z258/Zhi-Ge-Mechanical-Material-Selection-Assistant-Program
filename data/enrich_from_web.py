FIELDS = ["tensile_strength_mpa", "yield_strength_mpa", "elastic_modulus_gpa",
          "density_g_cm3", "hardness", "temperature_max_c", "elongation_percent",
          "thermal_conductivity_w_mk", "thermal_expansion_um_mk"]


def norm_grade(g):
    if not g:
        return ""
    s = str(g).strip()
    for suffix in (" (GB)", "(GB)", " (SS)", "(SS)", " (SN)", "(SN)"):
        s = s.replace(suffix, "")
    s = s.replace(", Rod", "").replace(" Alloy", "").strip()
    return s


def as_num(v):
    if v is None or v == "":
        return None
    try:
        f = float(v)
        return f
    except (TypeError, ValueError):
        return None


def main(apply=False):
    conn = sqlite3.connect(str(DB))
    conn.row_factory = sqlite3.Row
    rows = conn.execute("SELECT * FROM materials").fetchall()

    # 统计 section=99 中原“屈服强度”列的重复值：重复出现的多是导入占位值，
    # 不能当作抗拉强度搬移，直接置空更安全。
    from collections import Counter
    raw_yield = [r["yield_strength_mpa"] for r in rows if r["section"] == 99]
    ycount = Counter(v for v in raw_yield if v not in (None, ""))
    placeholder = {v for v, n in ycount.items() if n >= 3}

    updates = []          # (id, dict)
    moved = 0
    cleared = 0
    matched = 0
    unmatched_missing = {}

    for r in rows:
        mid = r["id"]
        grade = norm_grade(r["grade"] or r["name"])
        key = ALIASES.get(grade, grade)
        values = DATA.get(key)

        update = {}
        if values:
            matched += 1
            rm, re, e, rho, hb, tmax, elong, k, alpha = values
            update = {
                "tensile_strength_mpa": rm,
                "yield_strength_mpa": re,
                "elastic_modulus_gpa": e,
                "density_g_cm3": rho,
                "hardness": hb,
                "temperature_max_c": tmax,
                "elongation_percent": elong,
                "thermal_conductivity_w_mk": k,
                "thermal_expansion_um_mk": alpha,
            }
        else:
            # 未收录牌号：仅修复明显的列错位，不臆造数值
            tm = as_num(r["tensile_strength_mpa"])
            ym = as_num(r["yield_strength_mpa"])

            # 铸铁/铸钢牌号中的数字即最低抗拉强度，如 HT250 -> 250MPa
            import re
            cm = re.match(r"^(HT|QT|KTH|KTZ|KTB)(\d{3})", grade)
            if cm:
                n = float(cm.group(2))
                update = {"tensile_strength_mpa": n, "yield_strength_mpa": None}
                matched += 1
            elif r["section"] == 99:
                if tm is None and ym is not None and 100 <= ym <= 2200:
                    if r["yield_strength_mpa"] in placeholder:
                        # 重复占位值，判定不可靠，置空
                        update["yield_strength_mpa"] = None
                        cleared += 1
                    else:
                        update["tensile_strength_mpa"] = ym
                        update["yield_strength_mpa"] = None
                        moved += 1
                elif tm is not None and tm > 2500:
                    update["tensile_strength_mpa"] = None
                    cleared += 1
                if ym is not None and ym > 2200:
                    update["yield_strength_mpa"] = None
                    cleared += 1

        # 记录仍缺失的关键项
        if not update:
            for f in ("tensile_strength_mpa", "yield_strength_mpa", "hardness"):
                if r[f] in (None, ""):
                    unmatched_missing[f] = unmatched_missing.get(f, 0) + 1

        if update:
            update["source"] = SOURCE if values else (
                (r["source"] + "；" if r["source"] else "") + "列错位修复"
            )
            updates.append((mid, update))

    print(f"总材料数: {len(rows)}")
    print(f"命中权威数据牌号: {matched}")
    print(f"修复列错位(屈服->抗拉): {moved}")
    print(f"清除明显错误值: {cleared}")
    print(f"将更新行数: {len(updates)}")
    print("未收录牌号仍缺失(未处理):", unmatched_missing)

    if not apply:
        print("\n[预览模式] 未写入。使用 --apply 写库。")
        print("示例更新:")
        for mid, up in updates[:5]:
            print(" ", mid, up)
        conn.close()
        return

    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = DB.parent / "backups" / f"materials_backup_before_web_enrich_{ts}.db"
    backup.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(DB, backup)
    print(f"备份 -> {backup}")

    for mid, up in updates:
        sets = ", ".join(f"{k}=?" for k in up)
        conn.execute(f"UPDATE materials SET {sets} WHERE id=?", (*up.values(), mid))
    conn.commit()

    total = conn.execute("SELECT COUNT(*) FROM materials").fetchone()[0]
    for f in FIELDS:
        n = conn.execute(
            f"SELECT COUNT(*) FROM materials WHERE {f} IS NOT NULL AND {f} != ''"
        ).fetchone()[0]
        print(f"  {f}: {n}/{total} 已填")
    conn.close()
    print("完成。")


if __name__ == "__main__":
    main("--apply" in sys.argv)
